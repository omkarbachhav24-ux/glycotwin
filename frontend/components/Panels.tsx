const BAND_WORD: Record<string, string> = {
  high: "Above alert threshold",
  moderate: "Moderate",
  low: "Low",
  above_threshold: "Already above threshold",
  unknown: "Not available",
};

export function RiskPanel({ prediction }: { prediction: Prediction | null }) {
  if (!prediction) return <p className="empty">No prediction yet for this patient.</p>;
  const p = prediction.excursion_probability;
  return (
    <>
      <div className="risk-head">
        <span className="risk-value mono">
          {p === null ? "--" : `${(p * 100).toFixed(0)}%`}
        </span>
        <span className={`risk-tag ${prediction.risk_band}`}>
          {BAND_WORD[prediction.risk_band] ?? prediction.risk_band}
        </span>
      </div>
      <p style={{ marginTop: 12, marginBottom: 0 }}>{prediction.explanation}</p>

      <div className="metric-strip">
        <div>
          <div className="k">Event window</div>
          <div className="v mono">60 min</div>
        </div>
        <div>
          <div className="k">Threshold</div>
          <div className="v mono">{prediction.excursion_threshold_mg_dl} mg/dL</div>
        </div>
        <div>
          <div className="k">Projected crossing</div>
          <div className="v mono">
            {prediction.time_to_threshold_minutes === null
              ? "--"
              : `${prediction.time_to_threshold_minutes} min`}
          </div>
        </div>
        <div>
          <div className="k">Reading at</div>
          <div className="v mono">
            {new Date(prediction.observation_timestamp).toLocaleTimeString([], {
              hour: "2-digit", minute: "2-digit", hour12: false,
            })}
          </div>
        </div>
      </div>
      <p className="footnote">
        Probability is calibrated on held out validation patients. The projected crossing
        time is read off the forecast curve, not produced by a separate time to event
        model, so treat it as an estimate. This panel describes model output and does not
        recommend treatment.
      </p>
    </>
  );
}

export function ExplanationPanel({ contributors }: { contributors: Contributor[] }) {
  if (!contributors.length) {
    return <p className="empty">Contributions appear once the model has a full feature window.</p>;
  }
  const max = Math.max(...contributors.map((c) => Math.abs(c.contribution)), 0.0001);
  return (
    <>
      <div className="contrib">
        {contributors.map((c) => (
          <div className="contrib-row" key={c.feature}>
            <div className="contrib-label">
              {c.label}
              {c.value !== null && (
                <em className="mono"> at {c.value}</em>
              )}
            </div>
            <div className="contrib-track">
              <span className="contrib-axis" />
              <span
                className={`contrib-fill ${c.direction}`}
                style={{ width: `${(Math.abs(c.contribution) / max) * 50}%` }}
              />
            </div>
          </div>
        ))}
      </div>
      <p className="footnote">
        Bars to the right raise the modelled risk, bars to the left lower it. These are
        per prediction contributions from the gradient boosted classifier, which shows what
        the model weighted, not a causal account of this patient&apos;s physiology.
      </p>
    </>
  );
}

